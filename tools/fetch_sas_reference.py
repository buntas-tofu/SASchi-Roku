#!/usr/bin/env python3
"""fetch_sas_reference.py : harvest the SAS 9.4 reference docsets into kb/reference/.

Implements the design doc's extraction recipe (branch
design/conversion-reference, section 4.5) under ruling Q3: the enumerated
docsets first (stmt, dso), reconciled against the capability manifest's
reference_frame. Pure standard library plus pdftotext (poppler).

Per docset:
  1. download the pinned PDF (documentation.sas.com, public, no login) into
     kb/reference/pdfs/, sha256-stamped in PROVENANCE.json
  2. pdftotext -layout into kb/reference/extracted/<docset>/<docset>.txt
  3. entry list = the Dictionary section's column-0 headings ending in the
     docset's terminator word (" Statement", " Data Set Option"). Verified
     2026-11-02: the CONTENTS listing of BOTH docsets carries chapters only,
     so the design's dictionary-heading path governs both; the by-category
     index is the soft cross-check, the manifest universe the hard one.
  4. per-entry metadata from the field block (Valid in:, Category:/
     Categories:, Type:, Restriction:), continuation lines by indentation
  5. physical-to-logical page map from the running headers; one entry file
     per entry under entries/<slug>.md with YAML frontmatter (status:
     generated, entry, docset, page, physical_page, category, type,
     valid_in) and the pinned page's text from the heading down
  6. kb/reference/index.json : entry -> {docset, page, category, type,
     valid_in, file}, plus the pdf sha256 per docset

Contract (same shape as the other harvesters):
  --check   regenerate from the stored PDFs into a temp tree and compare
            against the committed files; exit 1 on drift; write nothing;
            no network
  plain run refresh: download only when a PDF is missing or --refresh;
            unchanged PDFs keep their original retrieved stamp
  --refresh force re-download of the PDFs

Determinism: every generated byte is a pure function of the PDF bytes.
Timestamps live only in PROVENANCE.json, which is rewritten only when the
PDF hash changes. Generated text carries the style floor normalization
(U+2014 to double hyphen, U+2026 to three dots), disclosed here and in the
harvest receipt: two punctuation characters, layout otherwise verbatim.
"""

import argparse
import hashlib
import json
import re
import shutil
import subprocess
import sys
import tempfile
import urllib.request
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
REF = ROOT / "kb" / "reference"

DOCSETS = {
    "stmt": {
        "docset_id": "lestmtsref",
        "terminator": " Statement",
        "title": "SAS 9.4 DATA Step Statements: Reference",
    },
    "dso": {
        "docset_id": "ledsoptsref",
        "terminator": " Data Set Option",
        "title": "SAS 9.4 Data Set Options: Reference, Fourth Edition",
    },
}
URL = "https://documentation.sas.com/api/docsets/{ds}/9.4/content/{ds}.pdf"
UA = "sas-ref harvest pipeline (https://github.com/buntas-tofu/SASchi-Roku)"

FIELD_LABELS = ("Valid in", "Category", "Categories", "Type", "Restriction",
                "Requirement", "See", "Note")


def floor_normalize(text: str) -> str:
    return text.replace("\u2014", "--").replace("\u2026", "...")


def sha256_file(p: Path) -> str:
    return hashlib.sha256(p.read_bytes()).hexdigest()


def download(docset_id: str, dest: Path) -> None:
    url = URL.format(ds=docset_id)
    req = urllib.request.Request(url, headers={"User-Agent": UA})
    with urllib.request.urlopen(req, timeout=180) as r, open(dest, "wb") as f:
        shutil.copyfileobj(r, f)


def pdftotext(pdf: Path) -> str:
    cmd = ["pdftotext", "-layout", str(pdf), "-"]
    out = subprocess.run(cmd, capture_output=True, check=True).stdout
    return out.decode("utf-8", "replace")


def pages_of(text: str) -> list:
    return text.split("\f")


def page_map(pages: list) -> dict:
    """physical (1-based) -> logical page number, from running headers."""
    m = {}
    for i, page in enumerate(pages, 1):
        for line in page.splitlines()[:4]:
            s = line.strip()
            if not s:
                continue
            tail = re.search(r"(\d+)\s*$", s)
            head = re.match(r"^(\d+)\s+\S", s)
            if head:
                m[i] = int(head.group(1))
                break
            if tail and not re.match(r"^[ivxlcdm]+$", s, re.I):
                m[i] = int(tail.group(1))
                break
    return m


def slugify(entry: str) -> str:
    e = entry.strip()
    if e.startswith("%"):
        e = "macro-" + e[1:]
    s = re.sub(r"[^A-Za-z0-9]+", "-", e.lower()).strip("-")
    return s or "entry"


SUBENTRY = re.compile(r"^[A-Z%][A-Za-z%()=/ -]* Statement: \S")
LABEL = re.compile(r"^\s{0,20}(Valid in|Category|Categories|Type|"
                   r"Restriction|Requirements?|See|Notes?):\s+(.*)$")
SECTIONISH = re.compile(r"^(Dictionary|Chapter|Table|Figure|Example|Appendix|Index)\b")


def is_candidate(name: str, terminator: str) -> bool:
    if not name or not (name[0].isupper() or name[0] == "%"):
        return False
    if SECTIONISH.match(name):
        return False
    if name.endswith(terminator) and name != terminator.strip():
        return True
    return bool(terminator.endswith(" Statement")) and bool(SUBENTRY.match(name))


def parse_entries(pages: list, pmap: dict, terminator: str) -> list:
    """Dictionary entries: column-0 candidate headings whose field block
    starts within a few lines, stopping at the next candidate heading."""
    entries = []
    for phys, page in enumerate(pages, 1):
        lines = page.splitlines()
        for li, line in enumerate(lines):
            if not line or line[0].isspace():
                continue
            name = line.strip()
            if not is_candidate(name, terminator):
                continue
            # join a wrapped heading: a short column-0 fragment on the next
            # line(s) that is not a label, not a candidate, not a sentence
            k = li + 1
            while k < len(lines):
                nl = lines[k]
                if not nl.strip() or nl[0].isspace():
                    break
                frag = nl.strip()
                if (len(frag) > 25 or frag.endswith(".") or LABEL.match(nl)
                        or is_candidate(frag, terminator)):
                    break
                name = name + " " + frag
                k += 1
            window = lines[li + 1:li + 40]
            tail = [l for l in lines[li + 1:] if l.strip()]
            if len(tail) < 3 and phys < len(pages):
                window = window + pages[phys].splitlines()[:25]
            fields = {}
            cur = None
            nonblank = 0
            for w in window:
                if w.strip():
                    nonblank += 1
                wstrip = w.strip()
                if (w and not w[0].isspace() and wstrip != name
                        and is_candidate(wstrip, terminator)):
                    break  # the next entry starts here
                if nonblank > 8 and not fields:
                    break  # prose, not a dictionary entry
                lab = LABEL.match(w)
                if lab:
                    cur = lab.group(1)
                    fields.setdefault(cur, lab.group(2).strip())
                    continue
                if cur and w.startswith(" " * 12) and wstrip and not wstrip.startswith("n "):
                    fields[cur] = (fields[cur] + " " + wstrip).strip()
                    continue
                if cur and not wstrip:
                    cur = None
                    continue
                if not cur and fields:
                    break  # field block complete; body text starts
            if not fields:
                continue  # a section or prose heading, not an entry
            cat = fields.get("Categories", fields.get("Category", ""))
            entries.append({
                "entry": name,
                "physical_page": phys,
                "page": pmap.get(phys, phys),
                "category": cat,
                "type": fields.get("Type", ""),
                "valid_in": fields.get("Valid in", ""),
                "restriction": fields.get("Restriction", ""),
                "slug": slugify(name),
            })
    seen = {}
    out = []
    for e in entries:
        if e["slug"] in seen:
            e = dict(e)
            e["slug"] = f"{e['slug']}-p{e['page']}"
            print(f"  note: slug disambiguated with a page suffix: {e['entry']} "
                  f"-> {e['slug']}")
            if e["slug"] in seen:
                print(f"  warning: hard slug collision, keeping first: {e['entry']}")
                continue
        seen[e["slug"]] = e
        out.append(e)
    return out


def entry_body(pages: list, e: dict) -> str:
    page = pages[e["physical_page"] - 1]
    lines = page.splitlines()
    start = None
    for i, l in enumerate(lines):
        if l.strip() == e["entry"] and (i == 0 or not l.startswith(" ")):
            start = i
            break
    if start is None:
        for i, l in enumerate(lines):
            if l.strip() == e["entry"]:
                start = i
                break
    body = "\n".join(lines[start:]) if start is not None else page
    return floor_normalize(body).rstrip() + "\n"


def frontmatter(e: dict, docset: str) -> str:
    fm = {
        "status": "generated",
        "entry": e["entry"],
        "docset": docset,
        "page": e["page"],
        "physical_page": e["physical_page"],
        "category": e["category"],
        "type": e["type"],
        "valid_in": e["valid_in"],
    }
    lines = ["---"]
    for k in ("status", "entry", "docset", "page", "physical_page",
              "category", "type", "valid_in"):
        v = fm[k]
        if isinstance(v, str):
            v = json.dumps(v)
        lines.append(f"{k}: {v}")
    lines.append("---")
    return "\n".join(lines) + "\n"


def build_docset(key: str, out_root: Path, now: str) -> dict:
    cfg = DOCSETS[key]
    ds_id = cfg["docset_id"]
    pdfs = out_root / "pdfs"
    pdfs.mkdir(parents=True, exist_ok=True)
    pdf = pdfs / f"{ds_id}.pdf"
    if not pdf.is_file():
        print(f"  downloading {ds_id}.pdf ...")
        download(ds_id, pdf)
    pdf_hash = sha256_file(pdf)
    text = pdftotext(pdf)
    pages = pages_of(text)
    pmap = page_map(pages)
    entries = parse_entries(pages, pmap, cfg["terminator"])
    exdir = out_root / "extracted" / key
    if (exdir / "entries").is_dir():
        shutil.rmtree(exdir / "entries")  # generated output: never leave orphans
    (exdir / "entries").mkdir(parents=True, exist_ok=True)
    (exdir / f"{ds_id}.txt").write_text(floor_normalize(text), encoding="utf-8")
    index = {}
    for e in entries:
        fname = f"{e['slug']}.md"
        (exdir / "entries" / fname).write_text(
            frontmatter(e, key) + "\n" + entry_body(pages, e), encoding="utf-8")
        index[e["entry"]] = {
            "docset": key,
            "page": e["page"],
            "category": e["category"],
            "type": e["type"],
            "valid_in": e["valid_in"],
            "file": f"extracted/{key}/entries/{fname}",
        }
    prov_dir = out_root / "extracted" / key
    old_prov = prov_dir / "PROVENANCE.json"
    retrieved = now
    if old_prov.is_file():
        try:
            old = json.loads(old_prov.read_text())
            if old.get("pdf_sha256") == pdf_hash:
                retrieved = old.get("retrieved_at", now)
        except json.JSONDecodeError:
            pass
    (prov_dir / "PROVENANCE.json").write_text(json.dumps({
        "docset": key,
        "docset_id": ds_id,
        "title": cfg["title"],
        "url": URL.format(ds=ds_id),
        "pdf_sha256": pdf_hash,
        "pdf_bytes": pdf.stat().st_size,
        "pdf_pages": len(pages) - (1 if pages and not pages[-1].strip() else 0),
        "retrieved_at": retrieved,
        "license": "SAS Institute public documentation; see the document's copyright page",
        "tool": "tools/fetch_sas_reference.py",
    }, indent=2) + "\n", encoding="utf-8")
    print(f"  {key}: {len(entries)} entries, {len(pages)} pages, pdf {pdf_hash[:12]}")
    return {"count": len(entries), "index": index, "pdf_sha256": pdf_hash}


def manifest_universes() -> dict:
    cm = ROOT / "kb" / "capability" / "capability-manifest.json"
    if not cm.is_file():
        return {}
    data = json.loads(cm.read_text())
    out = {}
    for d in data.get("reference_frame", {}).get("documents", []):
        if d.get("universe") is not None:
            out[d["id"]] = d["universe"]
    return out


def do_harvest(refresh: bool, only) -> int:
    now = datetime.now(timezone.utc).isoformat(timespec="seconds")
    if refresh:
        for key in (only or DOCSETS):
            pdf = REF / "pdfs" / f"{DOCSETS[key]['docset_id']}.pdf"
            if pdf.is_file():
                pdf.unlink()
    REF.mkdir(parents=True, exist_ok=True)
    results = {}
    for key in (only or list(DOCSETS)):
        results[key] = build_docset(key, REF, now)
    index = {
        "generated_by": "tools/fetch_sas_reference.py",
        "docsets": {k: {"pdf_sha256": v["pdf_sha256"], "count": v["count"],
                        "entries": v["index"]} for k, v in results.items()},
    }
    (REF / "index.json").write_text(json.dumps(index, indent=1, sort_keys=True) + "\n",
                                    encoding="utf-8")
    universes = manifest_universes()
    rc = 0
    for key, res in results.items():
        want = universes.get(key)
        if want is None:
            print(f"  reconcile {key}: manifest universe not enumerated (soft pass)")
        elif want == res["count"]:
            print(f"  reconcile {key}: {res['count']} == manifest universe {want}")
        else:
            print(f"  RECONCILE {key}: harvested {res['count']} != manifest universe {want}")
            rc = 1
    return rc


def do_check(only) -> int:
    if not (REF / "index.json").is_file():
        print("check: kb/reference/index.json missing; run the harvest first")
        return 1
    tmp = Path(tempfile.mkdtemp(prefix="sasref-check-"))
    drift = 0
    try:
        # regenerate into temp from the stored PDFs (no network)
        shutil.copytree(REF / "pdfs", tmp / "pdfs")
        for key in (only or list(DOCSETS)):
            live = REF / "extracted" / key / "PROVENANCE.json"
            if live.is_file():
                d = tmp / "extracted" / key
                d.mkdir(parents=True, exist_ok=True)
                shutil.copy(live, d / "PROVENANCE.json")
        now = "check"
        results = {}
        for key in (only or list(DOCSETS)):
            results[key] = build_docset(key, tmp, now)
        # compare generated trees (PROVENANCE retrieved_at may legitimately
        # differ only when the pdf hash differs, which the copy rules out)
        for key in results:
            for p in sorted((tmp / "extracted" / key).rglob("*")):
                if not p.is_file():
                    continue
                rel = p.relative_to(tmp)
                live = REF / rel
                if not live.is_file():
                    print(f"drift [{key}]: {rel} missing from the committed tree")
                    drift += 1
                elif p.read_bytes() != live.read_bytes():
                    print(f"drift [{key}]: {rel} differs from a fresh extraction")
                    drift += 1
        committed_index = json.loads((REF / "index.json").read_text())
        fresh = {"docsets": {k: {"pdf_sha256": v["pdf_sha256"], "count": v["count"],
                                 "entries": v["index"]} for k, v in results.items()}}
        if committed_index.get("docsets") != fresh["docsets"]:
            print("drift: index.json differs from a fresh extraction")
            drift += 1
    finally:
        shutil.rmtree(tmp, ignore_errors=True)
    if drift:
        print(f"check: {drift} drift finding(s); re-run the harvest to refresh")
        return 1
    print("check: the reference layer regenerates byte-identical from the stored PDFs")
    return 0


def main() -> int:
    ap = argparse.ArgumentParser(
        description="Harvest the SAS 9.4 reference docsets into kb/reference/.")
    ap.add_argument("--check", action="store_true",
                    help="verify the committed layer regenerates from the stored PDFs; no network")
    ap.add_argument("--refresh", action="store_true",
                    help="force re-download of the PDFs before harvesting")
    ap.add_argument("--docsets", default="",
                    help="comma-separated subset (default: all configured)")
    args = ap.parse_args()
    if not shutil.which("pdftotext"):
        print("error: pdftotext (poppler-utils) is required", file=sys.stderr)
        return 2
    only = [d.strip() for d in args.docsets.split(",") if d.strip()] or None
    if only:
        bad = [d for d in only if d not in DOCSETS]
        if bad:
            print(f"error: unknown docsets {bad}; configured: {sorted(DOCSETS)}",
                  file=sys.stderr)
            return 2
    if args.check:
        return do_check(only)
    rc = do_harvest(args.refresh, only)
    print("harvest: complete" if rc == 0 else "harvest: completed with reconcile failures")
    return rc


if __name__ == "__main__":
    sys.exit(main())
